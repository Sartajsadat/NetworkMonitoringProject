package gov.mot.netmon.audit;

/** Every auditable action. New phases add values here (capture start, firewall apply, ...). */
public enum AuditAction {
    // authentication
    AUTH_LOGIN,
    AUTH_LOGIN_FAILED,
    AUTH_LOGOUT,
    AUTH_TOKEN_REFRESH_REUSE_DETECTED,
    AUTH_PASSWORD_CHANGED,
    ACCESS_DENIED,
    // first-run setup
    SETUP_ADMIN_CREATED,
    SETUP_ATTEMPT_FAILED,
    // users
    USER_CREATED,
    USER_UPDATED,
    USER_ACTIVATED,
    USER_DEACTIVATED,
    USER_UNLOCKED,
    USER_PASSWORD_RESET,
    // servers
    SERVER_REGISTERED,
    SERVER_UPDATED,
    SERVER_DELETED,
    SERVER_GROUP_CREATED,
    SERVER_GROUP_UPDATED,
    SERVER_GROUP_DELETED,
    // agents
    AGENT_ENROLLMENT_TOKEN_CREATED,
    AGENT_ENROLLED,
    AGENT_ENROLLMENT_FAILED,
    AGENT_REVOKED,
    AGENT_CREDENTIALS_ROTATED,
    AGENT_CONFIG_UPDATED,
    AGENT_AUTH_FAILED,
    // packet captures
    CAPTURE_REQUESTED,
    CAPTURE_STOP_REQUESTED,
    CAPTURE_STATUS_CHANGED,
    CAPTURE_VIEWED,
    CAPTURE_PACKET_BYTES_VIEWED,
    CAPTURE_DOWNLOADED,
    CAPTURE_FILES_DELETED,
    // alerts
    ALERT_RULE_CREATED,
    ALERT_RULE_UPDATED,
    ALERT_RULE_DELETED,
    ALERT_ACKNOWLEDGED,
    ALERT_RESOLVED
}
